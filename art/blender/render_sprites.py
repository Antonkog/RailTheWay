def shot_trees():
    reset_scene(transparent=False)
    add_grass_base()
    trunk = material("TRUNK", (0.20, 0.12, 0.06), 0.95)
    leaf_dark = material("LEAF_DARK", (0.10, 0.30, 0.14), 0.90)
    leaf_mid = material("LEAF_MID", (0.16, 0.40, 0.20), 0.90)
    leaf_light = material("LEAF_LIGHT", (0.24, 0.52, 0.26), 0.90)

    def fir(x, y, scale, seed):
        local = random.Random(seed)
        add_cylinder(f"TRUNK_{x}_{y}", 0.022 * scale, 0.16 * scale,
                     (x, y, 0.08 * scale), trunk, vertices=8)
        # Radial lower branches give a conifer a star-like top-down silhouette.
        for i in range(8):
            ang = i * math.tau / 8.0 + local.uniform(-0.12, 0.12)
            radius = 0.13 * scale
            branch = add_ico(
                f"BRANCH_{x}_{y}_{i}", 0.085 * scale,
                (x + math.cos(ang) * radius, y + math.sin(ang) * radius, 0.145 * scale),
                leaf_mid if i % 2 == 0 else leaf_dark, subdiv=1,
            )
            branch.scale = (1.55, 0.55, 0.40)
            branch.rotation_euler = (0.0, 0.0, ang)
        for i in range(6):
            ang = i * math.tau / 6.0 + 0.25
            radius = 0.075 * scale
            branch = add_ico(
                f"BRANCH_TOP_{x}_{y}_{i}", 0.070 * scale,
                (x + math.cos(ang) * radius, y + math.sin(ang) * radius, 0.215 * scale),
                leaf_light if i % 2 == 0 else leaf_mid, subdiv=1,
            )
            branch.scale = (1.45, 0.55, 0.38)
            branch.rotation_euler = (0.0, 0.0, ang)
        add_ico(f"TOP_{x}_{y}", 0.060 * scale, (x, y, 0.275 * scale), leaf_light, subdiv=2)

    fir(-0.19, 0.10, 1.00, 11)
    fir(0.18, -0.07, 0.78, 22)
    fir(0.02, 0.29, 0.60, 33)
    render("trees_topdown", model_name="forest_topdown")


def shot_tree_icon():
    """A 3/4-view pine icon, composited over the grass tile by postprocess_sprites.py."""
    reset_scene(transparent=True, ortho=1.0, camera_pos=(0.0, -1.55, 1.30), target=(0.0, 0.0, 0.24))
    trunk = material("TRUNK", (0.20, 0.12, 0.06), 0.95)
    pine_dark = material("PINE_DARK", (0.10, 0.30, 0.14), 0.90)
    pine_mid = material("PINE_MID", (0.16, 0.40, 0.20), 0.90)
    pine_light = material("PINE_LIGHT", (0.24, 0.52, 0.26), 0.90)

    def pine(x, y, scale):
        add_cylinder(f"TRUNK_{x}_{y}", 0.025 * scale, 0.18 * scale,
                     (x, y, 0.09 * scale), trunk, vertices=8)
        for i, (radius, height, z) in enumerate([
            (0.19, 0.24, 0.22),
            (0.15, 0.20, 0.35),
            (0.10, 0.17, 0.46),
        ]):
            add_cone(f"PINE_{x}_{y}_{i}", radius * scale, 0.003, height * scale,
                     (x, y, z * scale), pine_dark if i % 2 == 0 else (pine_mid if i == 1 else pine_light),
                     vertices=10)

    pine(-0.17, 0.05, 1.00)
    pine(0.17, -0.05, 0.80)
    pine(0.01, 0.22, 0.62)
    render("tree_icon", model_name="forest")


