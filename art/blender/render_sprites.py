"""Render a small, experimental Blender sprite set for RailTheWay.

This is an *asset experiment*, not part of the Gradle build. It writes PNGs to
art/renders/raw/, saves editable .blend sources and portable .glb models to
art/models/, and does not touch assets/sprites/. Run it with:

    blender --background --factory-startup --python art/blender/render_sprites.py

The game renders 32 px tiles; these sources are 256 px so the same art can also be
used at a larger tile size or with mipmaps later.
"""

import math
import os
import random

import bpy
from mathutils import Vector

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "art", "renders", "raw")
MODELS = os.path.join(ROOT, "art", "models")
SIZE = 256
os.makedirs(OUT, exist_ok=True)
os.makedirs(MODELS, exist_ok=True)
random.seed(1234)


# --------------------------------------------------------------------------- scene

def reset_scene(transparent=True, ortho=1.0, camera_pos=(0.0, 0.0, 10.0), target=(0.0, 0.0, 0.0)):
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.render.engine = "BLENDER_EEVEE"
    scene.render.resolution_x = SIZE
    scene.render.resolution_y = SIZE
    scene.render.resolution_percentage = 100
    scene.render.film_transparent = transparent
    scene.render.image_settings.file_format = "PNG"
    scene.render.image_settings.color_mode = "RGBA" if transparent else "RGB"
    scene.render.image_settings.color_depth = "8"
    scene.render.image_settings.compression = 15
    scene.view_settings.view_transform = "Standard"
    scene.view_settings.look = "None"
    scene.view_settings.exposure = 0.15
    # EEVEE Next settings are version dependent; ignore missing knobs.
    for attr, value in (("taa_render_samples", 64), ("use_shadows", True)):
        try:
            setattr(scene.eevee, attr, value)
        except Exception:
            pass

    world = bpy.data.worlds.new("WORLD")
    scene.world = world
    world.use_nodes = True
    bg = world.node_tree.nodes["Background"]
    bg.inputs["Color"].default_value = (0.45, 0.47, 0.50, 1.0)
    bg.inputs["Strength"].default_value = 0.55

    key_data = bpy.data.lights.new("KEY", "SUN")
    key_data.energy = 3.2
    key_data.angle = math.radians(12)
    key = bpy.data.objects.new("KEY", key_data)
    scene.collection.objects.link(key)
    key.rotation_euler = (math.radians(38), math.radians(8), math.radians(28))

    fill_data = bpy.data.lights.new("FILL", "SUN")
    fill_data.energy = 1.3
    fill_data.angle = math.radians(45)
    fill = bpy.data.objects.new("FILL", fill_data)
    scene.collection.objects.link(fill)
    fill.rotation_euler = (math.radians(62), math.radians(-10), math.radians(-125))

    front_data = bpy.data.lights.new("FRONT", "SUN")
    front_data.energy = 0.6
    front_data.angle = math.radians(60)
    front = bpy.data.objects.new("FRONT", front_data)
    scene.collection.objects.link(front)
    front.rotation_euler = (math.radians(65), 0.0, 0.0)

    cam_data = bpy.data.cameras.new("CAM")
    cam_data.type = "ORTHO"
    cam_data.ortho_scale = ortho
    cam = bpy.data.objects.new("CAM", cam_data)
    scene.collection.objects.link(cam)
    cam.location = camera_pos
    direction = Vector(target) - cam.location
    cam.rotation_euler = direction.to_track_quat("-Z", "Y").to_euler()
    scene.camera = cam
    return scene


def save_model(name):
    """Save the current scene as an editable .blend and a portable .glb."""
    # Do not create .blend1 backups; the whole set is regenerated by the script.
    bpy.context.preferences.filepaths.save_version = 0
    scene = bpy.context.scene
    bpy.ops.object.select_all(action="DESELECT")
    meshes = [obj for obj in scene.objects if obj.type == "MESH"]
    for obj in meshes:
        obj.select_set(True)
    if meshes:
        bpy.context.view_layer.objects.active = meshes[0]

    blend_path = os.path.join(MODELS, name + ".blend")
    bpy.ops.wm.save_as_mainfile(filepath=blend_path)

    glb_path = os.path.join(MODELS, name + ".glb")
    bpy.ops.export_scene.gltf(
        filepath=glb_path,
        export_format="GLB",
        use_selection=True,
        export_apply=True,
    )
    print("SAVED MODEL", name)


def render(name, model_name=None):
    save_model(model_name or name)
    scene = bpy.context.scene
    scene.render.filepath = os.path.join(OUT, name + ".png")
    bpy.ops.render.render(write_still=True)
    print("RENDERED", name)


# ----------------------------------------------------------------------- materials

def srgb_to_linear(color):
    def channel(x):
        return x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4
    return tuple(channel(x) for x in color)


def material(name, color, roughness=0.8, metallic=0.0, emission=0.0):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    lin = srgb_to_linear(color)
    bsdf.inputs["Base Color"].default_value = (*lin, 1.0)
    bsdf.inputs["Roughness"].default_value = roughness
    bsdf.inputs["Metallic"].default_value = metallic
    if emission:
        try:
            bsdf.inputs["Emission Color"].default_value = (*lin, 1.0)
            bsdf.inputs["Emission Strength"].default_value = emission
        except Exception:
            pass
    return mat


def link_noise(mat, scale, low, high, bump_strength):
    nt = mat.node_tree
    nodes, links = nt.nodes, nt.links
    bsdf = nodes.get("Principled BSDF")
    noise = nodes.new("ShaderNodeTexNoise")
    noise.inputs["Scale"].default_value = scale
    noise.inputs["Detail"].default_value = 3.0
    noise.inputs["Roughness"].default_value = 0.55
    ramp = nodes.new("ShaderNodeValToRGB")
    ramp.color_ramp.elements[0].position = 0.34
    ramp.color_ramp.elements[0].color = (*srgb_to_linear(low), 1.0)
    ramp.color_ramp.elements[1].position = 0.74
    ramp.color_ramp.elements[1].color = (*srgb_to_linear(high), 1.0)
    links.new(noise.outputs["Fac"], ramp.inputs["Fac"])
    links.new(ramp.outputs["Color"], bsdf.inputs["Base Color"])
    bump = nodes.new("ShaderNodeBump")
    bump.inputs["Strength"].default_value = bump_strength
    links.new(noise.outputs["Fac"], bump.inputs["Height"])
    links.new(bump.outputs["Normal"], bsdf.inputs["Normal"])


def link_shingles(mat):
    nt = mat.node_tree
    nodes, links = nt.nodes, nt.links
    bsdf = nodes.get("Principled BSDF")
    brick = nodes.new("ShaderNodeTexBrick")
    brick.inputs["Scale"].default_value = 18.0
    brick.inputs["Mortar Size"].default_value = 0.018
    brick.inputs["Color1"].default_value = (*srgb_to_linear((0.32, 0.24, 0.21)), 1.0)
    brick.inputs["Color2"].default_value = (*srgb_to_linear((0.24, 0.17, 0.15)), 1.0)
    brick.inputs["Mortar"].default_value = (*srgb_to_linear((0.10, 0.07, 0.06)), 1.0)
    links.new(brick.outputs["Color"], bsdf.inputs["Base Color"])
    bump = nodes.new("ShaderNodeBump")
    bump.inputs["Strength"].default_value = 0.35
    links.new(brick.outputs["Fac"], bump.inputs["Height"])
    links.new(bump.outputs["Normal"], bsdf.inputs["Normal"])


# --------------------------------------------------------------------------- meshes

def set_flat(obj, smooth=False):
    for poly in obj.data.polygons:
        poly.use_smooth = smooth


def add_cube(name, dims, loc, mat, rot=(0.0, 0.0, 0.0)):
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=loc, rotation=rot)
    obj = bpy.context.object
    obj.name = name
    obj.scale = dims
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    obj.data.materials.append(mat)
    set_flat(obj, False)
    return obj


def bevel(obj, width=0.02, segments=2):
    mod = obj.modifiers.new("BEVEL", "BEVEL")
    mod.width = width
    mod.segments = segments
    return obj


def add_plane(name, size, loc, mat):
    bpy.ops.mesh.primitive_plane_add(size=size, location=loc)
    obj = bpy.context.object
    obj.name = name
    obj.data.materials.append(mat)
    return obj


def add_cylinder(name, radius, depth, loc, mat, rot=(0.0, 0.0, 0.0), vertices=16, smooth=False):
    bpy.ops.mesh.primitive_cylinder_add(
        vertices=vertices, radius=radius, depth=depth, location=loc, rotation=rot
    )
    obj = bpy.context.object
    obj.name = name
    obj.data.materials.append(mat)
    set_flat(obj, smooth)
    return obj


def add_cone(name, r1, r2, depth, loc, mat, vertices=10):
    bpy.ops.mesh.primitive_cone_add(
        vertices=vertices, radius1=r1, radius2=r2, depth=depth, location=loc
    )
    obj = bpy.context.object
    obj.name = name
    obj.data.materials.append(mat)
    set_flat(obj, False)
    return obj


def add_ico(name, radius, loc, mat, subdiv=1):
    bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=subdiv, radius=radius, location=loc)
    obj = bpy.context.object
    obj.name = name
    obj.data.materials.append(mat)
    set_flat(obj, False)
    return obj


def add_gable_roof(name, width, depth, base_z, ridge_z, mat):
    hw, hd = width / 2.0, depth / 2.0
    verts = [
        (-hw, -hd, base_z), (hw, -hd, base_z), (hw, hd, base_z), (-hw, hd, base_z),
        (0.0, -hd, ridge_z), (0.0, hd, ridge_z),
    ]
    faces = [
        (0, 1, 4),       # front gable
        (3, 5, 2),       # back gable
        (0, 4, 5, 3),    # left slope
        (1, 2, 5, 4),    # right slope
        (0, 3, 2, 1),    # underside
    ]
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.validate()
    mesh.update()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    obj.data.materials.append(mat)
    set_flat(obj, False)
    return obj


def add_wave_ribbon(name, y0, amplitude, wavelength, phase, width, mat, z=0.006):
    verts, faces = [], []
    n = 48
    for i in range(n + 1):
        x = -0.48 + 0.96 * i / n
        y = y0 + amplitude * math.sin((x / wavelength) * math.tau + phase)
        verts.append((x, y - width / 2.0, z))
        verts.append((x, y + width / 2.0, z))
    for i in range(n):
        a = 2 * i
        faces.append((a, a + 1, a + 3, a + 2))
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.validate()
    mesh.update()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    obj.data.materials.append(mat)
    return obj


