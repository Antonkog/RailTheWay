def add_grass_base(tufts=0, flowers=0):
    grass = material("GRASS", (0.34, 0.62, 0.27), 0.95)
    add_plane("GRASS", 1.04, (0.0, 0.0, 0.0), grass)
    link_noise(
        grass, 5.5,
        (0.31, 0.56, 0.24),
        (0.42, 0.70, 0.32),
        0.08,
    )
    tuft_mat = material("TUFT", (0.24, 0.48, 0.18), 1.0)
    for i in range(tufts):
        x = random.uniform(-0.46, 0.46)
        y = random.uniform(-0.46, 0.46)
        h = random.uniform(0.03, 0.06)
        add_cone(f"TUFT_{i}", 0.012, 0.001, h, (x, y, h * 0.5), tuft_mat, vertices=5)
    flower_mats = [
        material("FLOWER_Y", (0.95, 0.85, 0.20), 1.0),
        material("FLOWER_P", (0.92, 0.50, 0.70), 1.0),
    ]
    for i in range(flowers):
        x = random.uniform(-0.40, 0.40)
        y = random.uniform(-0.40, 0.40)
        add_ico(f"FLOWER_{i}", 0.014, (x, y, 0.025), flower_mats[i % 2], subdiv=1)
    return grass


def shot_grass():
    reset_scene(transparent=False)
    add_grass_base(tufts=22, flowers=6)
    render("grass")


